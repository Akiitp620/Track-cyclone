export function calculateHazard(scenario, asset, geoContext = null) {
  const trackX = 50 + scenario.trackShift;
  const distance = Math.abs(asset.x - trackX);
  
  const mapRadius = scenario.radius / 4.8;
  let distanceFactor = 1 - (distance / mapRadius);
  if (distanceFactor < 0) distanceFactor = 0;
  
  const windFactor = Math.min(scenario.windSpeed / 350, 1);
  const rainFactor = Math.min(scenario.rainfall / 1000, 1);
  
  let coastalFactor = 1.0;
  if (geoContext && geoContext[asset.id]) {
    // Context-driven coastal exposure multiplier (1.0 to 1.5)
    coastalFactor = 1.0 + (geoContext[asset.id].coastalExposure * 0.5);
  } else {
    coastalFactor = asset.y > 70 ? 1.2 : 1.0;
  }
  
  let hazard = (windFactor * 0.6 + rainFactor * 0.4) * distanceFactor * coastalFactor;
  return Math.min(Math.max(hazard, 0), 1);
}

export function calculateExposure(asset) {
  const popFactor = Math.min(asset.populationServed / 100000, 1.5);
  const critFactor = asset.criticality / 5;
  const accessFactor = Math.max(1 - (asset.accessRoutes - 1) * 0.2, 0.2);

  return (popFactor * 0.4 + critFactor * 0.4 + accessFactor * 0.2);
}

export function calculateRisk(scenario, asset, geoContext = null) {
  const hazard = calculateHazard(scenario, asset, geoContext);
  const exposure = calculateExposure(asset);
  
  let rawRisk = hazard * exposure * asset.baseVulnerability * 100;
  const categoryMultiplier = 1 + (scenario.category * 0.15);
  rawRisk *= categoryMultiplier;
  
  const riskScore = Math.min(Math.max(Math.round(rawRisk), 0), 100);
  
  return {
    ...asset,
    hazard: Number(hazard.toFixed(2)),
    exposure: Number(exposure.toFixed(2)),
    risk: riskScore,
    category: getRiskCategory(riskScore)
  };
}

export function getRiskCategory(score) {
  if (score > 80) return 'CRITICAL';
  if (score > 60) return 'HIGH';
  if (score > 30) return 'MEDIUM';
  return 'LOW';
}

export function getScenarioCategory(windSpeed) {
  if (windSpeed < 119) return 0;
  if (windSpeed <= 153) return 1;
  if (windSpeed <= 177) return 2;
  if (windSpeed <= 208) return 3;
  if (windSpeed <= 251) return 4;
  return 5;
}
